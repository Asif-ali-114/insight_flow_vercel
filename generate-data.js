// ---------- seeded PRNG ----------
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20250101);
const rint = (a, b) => a + Math.floor(rand() * (b - a + 1));
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
function wpick(items, weights) {
  const total = weights.reduce((s, w) => s + w, 0);
  let r = rand() * total;
  for (let i = 0; i < items.length; i++) { r -= weights[i]; if (r <= 0) return items[i]; }
  return items[items.length - 1];
}
const r2 = (n) => Math.round(n * 100) / 100;
const pad = (n, w) => String(n).padStart(w, "0");
const YEAR = 2025;
const monthKey = (m) => YEAR + "-" + pad(m + 1, 2);
const dim = (m) => new Date(YEAR, m + 1, 0).getDate();

function csvCell(v) {
  if (v === null || v === undefined) return "";
  const s = String(v);
  return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
}
function toCsv(columns, rows) {
  return [columns.join(",")].concat(rows.map((r) => columns.map((c, i) => csvCell(Array.isArray(r) ? r[i] : r[c])).join(","))).join("\n") + "\n";
}
function writeData(key, payload, csv) {
  fs.writeFileSync(path.join(OUT, key + ".js"),
    "/* Synthetic sample data (generated by tools/generate-data.js). Not real business data. */\n" +
    "window.IF_DATA = window.IF_DATA || {};\nwindow.IF_DATA." + key + " = " + JSON.stringify(payload) + ";\n");
  if (csv) fs.writeFileSync(path.join(OUT, key + ".csv"), csv);
}

